/** Fields of the Driver Details screen (Branch is intentionally left out). The Driver Number is generated by the server. */
export interface DriverFormState {
  driverName: string; address: string; mobile: string; accountName: string; accountNumber: string; ifscCode: string; bankName: string;
  licenceNumber: string; licenceType: string; licenceExpiryDate: string; attachment: Attachment | null;
  driverType: "" | DriverType; salary: string; status: "ACTIVE" | "INACTIVE";
  availability: DriverAvForm; // Driver Availability & Status section
}

export const emptyDriverForm = (): DriverFormState => ({
  driverName: "", address: "", mobile: "", accountName: "", accountNumber: "", ifscCode: "", bankName: "", licenceNumber: "", licenceType: "",
  licenceExpiryDate: "", attachment: null, driverType: "", salary: "", status: "ACTIVE", availability: emptyDriverAvailability(),
});

// ---- keyboard sanitisers (stop clearly invalid characters while typing, without over-restricting)
export const sanitizeName = (raw: string): string => raw.replace(/[^\p{L} .'-]/gu, "").slice(0, 80);
export const sanitizeDigits = (raw: string, max = 20): string => raw.replace(/[^0-9]/g, "").slice(0, max);
export const sanitizeIfsc = (raw: string): string => raw.toUpperCase().replace(/[^A-Z0-9]/g, "").slice(0, 11);
export const sanitizeLicence = (raw: string): string => raw.toUpperCase().replace(/[^A-Z0-9 \-/]/g, "").slice(0, 24);
export const sanitizeSalary = (raw: string): string => {
  const cleaned = raw.replace(/[^0-9.]/g, "");
  const [whole, ...rest] = cleaned.split(".");
  return (rest.length ? `${whole}.${rest.join("").slice(0, 2)}` : whole).slice(0, 10);
};
export { sanitizePhoneInput };

const realDate = (v: string) => /^\d{4}-\d{2}-\d{2}$/.test(v) && new Date(`${v}T00:00:00Z`).toISOString().slice(0, 10) === v;
export const licenceKey = (raw: string): string => raw.toUpperCase().replace(/[\s\-/]/g, "");

/** Mirrors the server rules; the server stays the authority. */
export function validateDriverForm(f: DriverFormState): string[] {
  const e: string[] = [];
  const name = f.driverName.trim();
  if (!name) e.push("Driver name is required");
  else if (name.length < 2 || !/^\p{L}[\p{L} .'-]*$/u.test(name)) e.push("Driver name may contain letters, spaces, dots, apostrophes and hyphens only");
  if (!f.driverType) e.push("Driver type is required");
  if (!f.mobile) e.push("Mobile number is required");
  else if (!isValidPhone(f.mobile)) e.push("Mobile number must be a valid 10-digit Indian mobile number (+91)");
  if (f.accountNumber && !/^[0-9]{6,20}$/.test(f.accountNumber)) e.push("Account number must be 6 to 20 digits");
  if (f.ifscCode && !/^[A-Z]{4}0[A-Z0-9]{6}$/.test(f.ifscCode.toUpperCase())) e.push("IFSC code is not valid (e.g. SBIN0001234)");
  if (f.licenceNumber.trim()) {
    const k = licenceKey(f.licenceNumber);
    if (!/^[A-Z0-9]{8,20}$/.test(k) || !/[0-9]/.test(k) || !/[A-Z]/.test(k)) e.push("Licence number is not valid (e.g. TN0720110012345)");
  }
  if (f.licenceExpiryDate && !realDate(f.licenceExpiryDate)) e.push("Licence expiry date is not a valid date");
  if (f.salary && !(Number(f.salary) >= 0 && Number(f.salary) <= 9_999_999.99)) e.push("Salary must be a number between 0 and 9999999.99");
  e.push(...validateDriverAvailability(f.availability));
  return e;
}

export function toDriverPayload(f: DriverFormState, includeStatus: boolean) {
  const a = f.attachment;
  return {
    driverName: f.driverName.trim(), driverType: f.driverType, address: f.address, mobileNumber: toFullPhone(f.mobile),
    accountName: f.accountName, accountNumber: f.accountNumber, ifscCode: f.ifscCode, bankName: f.bankName,
    licenceNumber: f.licenceNumber, licenceType: f.licenceType, licenceExpiryDate: f.licenceExpiryDate, salary: f.salary,
    attachment: a ? { storage: a.storage, key: a.key, name: a.name, size: a.size, mimeType: a.mimeType } : null, // url is computed by the server
    ...(includeStatus ? { status: f.status } : {}),
    availability: toDriverAvailabilityPayload(f.availability),
  };
}

const s = (v: unknown) => (v === null || v === undefined ? "" : String(v));
/** Restores every saved value into the form (Edit Driver). */
export function fromDriver(d: Partial<Driver>): DriverFormState {
  return {
    driverName: s(d.driverName), address: s(d.address), mobile: fromStoredPhone(d.mobileNumber), accountName: s(d.accountName), accountNumber: s(d.accountNumber),
    ifscCode: s(d.ifscCode), bankName: s(d.bankName), licenceNumber: s(d.licenceNumber), licenceType: s(d.licenceType), licenceExpiryDate: s(d.licenceExpiryDate),
    attachment: d.attachment ?? null, driverType: d.driverType === "COMPANY_DRIVER" || d.driverType === "ACTING_DRIVER" ? d.driverType : "",
    salary: d.salary === null || d.salary === undefined ? "" : String(d.salary), status: d.status === "INACTIVE" ? "INACTIVE" : "ACTIVE",
    availability: fromDriverAvailability(d.availability),
  };
}

export const fmtLicenceExpiry = (v?: string | null): string => (v ? formatDate(v) : "—");
