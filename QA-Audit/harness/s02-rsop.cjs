const fs = require("fs");
const { scenario, tc, sleep, todayIst, addDays, api } = require("./qa.cjs");
const STAMP = Date.now().toString(36).slice(-5).toUpperCase();
const STATE = "./state.json";
const state = fs.existsSync(STATE) ? JSON.parse(fs.readFileSync(STATE, "utf8")) : {};
(async () => {
  await scenario("S02-rsop-project-creation", async (s) => {
    await s.uiLogin("RSOP");
    await s.goto("/rsop/new");
    await tc(s, "RSOP-01", "RoadShow form: Next with empty mandatory fields shows every error", "RSOP", async (t) => {
      await s.clickText(".type-pick strong", "Roadshow");
      await s.clickText(".sticky-actions button", "Next");
      const err = await s.text(".alert");
      t.note(err.replace(/\n/g, " | "));
      t.expect(/Billing name is required/.test(err) && /State code is required/.test(err) && /Number of vans/.test(err) && /dates are required/.test(err), "missing validation messages");
      await t.shot("roadshow-empty");
    });
    await tc(s, "RSOP-02", "RoadShow form: End date before Start date is rejected", "RSOP", async (t) => {
      await s.fill("Billing Name", `QA Test Roadshow ${STAMP}`);
      await s.fill("State Code", "33");
      await s.fill("Number of Vans", "1");
      await s.date("Start Date", addDays(todayIst(), 10));
      await s.date("End Date", addDays(todayIst(), 2));
      await s.date("Reporting Date", addDays(todayIst(), 1));
      await s.clickText(".sticky-actions button", "Next");
      const err = await s.text(".alert");
      t.note(err);
      t.expect(/End date cannot be before start date/.test(err), "date order not validated");
      await t.shot("end-before-start");
    });
    await tc(s, "RSOP-03", "RoadShow: valid request creates trackup / PIF / display numbers", "RSOP", async (t) => {
      await s.date("Start Date", addDays(todayIst(), 1));
      await s.date("End Date", addDays(todayIst(), 12));
      await s.clickText(".sticky-actions button", "Next");
      t.expect(!(await s.page.$(".alert")), "step 1 still has errors");
      await s.page.type('input[placeholder="Type or pick a location, press Enter"]', "Chennai – T Nagar");
      await s.page.keyboard.press("Enter");
      await s.fill("Reporting Person Name", "QA Coordinator");
      await s.clickText(".sticky-actions button", "Next");
      await s.clickText(".sticky-actions button", "Create Trackup Numbers");
      await t.shot("confirm-dialog");
      await s.clickText(".modal button", "Create", { exact: true });
      await sleep(1500);
      const modal = await s.text(".modal");
      const nums = modal.match(/JS-\d+\/\d{4}-\d{2}/g) ?? [];
      t.note(`created: ${nums.join(", ")}`);
      t.expect(nums.length >= 1, "no trackup number shown");
      state.roadshow = { billingName: `QA Test Roadshow ${STAMP}`, trackup: nums[0] };
      await t.shot("created-numbers");
      await s.clickText(".modal button", "Go to dashboard");
      await sleep(800);
    });
    await tc(s, "RSOP-04", "Signage form: mandatory fields + To date before From date are validated", "RSOP", async (t) => {
      await s.goto("/rsop/new");
      await s.clickText(".type-pick strong", "Signage");
      const dflt = await s.page.evaluate(() => [...document.querySelectorAll("label")].find((l) => l.textContent.trim().startsWith("Date"))?.querySelector("input.ui-native")?.value);
      t.note(`default "Date" field value: ${dflt} (IST today ${todayIst()})`);
      await s.fill("Client", `QA Test Signage ${STAMP}`);
      await s.date("From Date", addDays(todayIst(), 5));
      await s.date("To Date", addDays(todayIst(), 1));
      await s.clickText("button.btn-primary", "Create");
      await sleep(500);
      if (await s.page.$(".modal")) await s.clickText(".modal button", "Create", { exact: true });
      await sleep(500);
      const err = await s.text(".alert");
      t.note(err.replace(/\n/g, " | "));
      t.expect(/Job sheet number is required/.test(err) && /To date cannot be before from date/.test(err), "signage validation missing");
      await t.shot("signage-invalid");
    });
    await tc(s, "RSOP-05", "Signage: valid request is created", "RSOP", async (t) => {
      await s.fill("Job Sheet Number", `QA${STAMP}`);
      await s.fill("Location", "Coimbatore");
      await s.fill("Number of Vehicles", "1");
      await s.date("From Date", addDays(todayIst(), 1));
      await s.date("To Date", addDays(todayIst(), 9));
      await s.clickText("button.btn-primary", "Create");
      await sleep(400);
      await s.clickText(".modal button", "Create", { exact: true });
      await sleep(1500);
      const nums = (await s.text(".modal")).match(/JS-\d+\/\d{4}-\d{2}/g) ?? [];
      t.note(`created: ${nums.join(", ")}`);
      t.expect(nums.length >= 1, "no trackup number");
      state.signage = { client: `QA Test Signage ${STAMP}`, trackup: nums[0], jobSheet: `QA${STAMP}` };
      await t.shot("signage-created");
      await s.clickText(".modal button", "Go to dashboard");
      await sleep(800);
    });
    await tc(s, "RSOP-06", "Dashboard: new requests are listed; search (debounced) and type cards filter the table", "RSOP", async (t) => {
      await s.goto("/rsop");
      await s.page.type(".filters input, .card input", STAMP, { delay: 40 });
      await sleep(900);
      await s.waitIdle();
      const rows = await s.page.$$eval("table tbody tr", (r) => r.map((x) => x.innerText.replace(/\s+/g, " ").slice(0, 120)));
      t.note(`rows for "${STAMP}": ${rows.length}`);
      t.expect(rows.length === 2, `expected the 2 QA requests, got ${rows.length}`);
      await t.shot("search");
      await s.clickText("button.stat span", "Signage");
      await s.waitIdle();
      const after = await s.page.$$eval("table tbody tr", (r) => r.length);
      t.note(`after Signage card: ${after} row(s)`);
      t.expect(after === 1, "type card did not filter");
      await t.shot("signage-card-filter");
    });
    await tc(s, "RSOP-07", "Project detail view opens with every captured field", "RSOP", async (t) => {
      const btn = await s.page.$("table tbody tr button");
      if (!btn) t.blocked("no row action button");
      await btn.click();
      await sleep(600);
      const m = await s.text(".modal");
      t.note(m.slice(0, 160).replace(/\n/g, " | "));
      t.expect(m.includes(state.signage.jobSheet), "job sheet number not shown in detail");
      await t.shot("detail");
      await s.page.keyboard.press("Escape");
    });
    fs.writeFileSync(STATE, JSON.stringify(state, null, 2));
  });
})();
